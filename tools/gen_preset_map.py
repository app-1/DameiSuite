"""Phase 0: canonical producer preset map.

Parses every producer-preset slider declaration in effects/*.jsfx, normalises each
name to a canonical producer id, and emits:
  - tools/preset_map.json            (machine-readable map + mismatch report)
  - effects/Damei_PresetMap.jsfx-inc (EEL translation functions for `import`)
Run:  python tools/gen_preset_map.py
"""
import re, os, json, glob

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FX = os.path.join(ROOT, "effects")

# Order matters: more specific rules first.
RULES = [
    ("default",     r"^\s*default|^\s*0:\s*default"),
    ("fish",        r"jordan fish"),
    ("pinchin",     r"split chain|pinchin"),
    ("staticdress", r"static dress|bickerstaffe"),
    ("blanket",     r"blanket|love is noise|lewis johns|grant berry"),
    ("prenc",       r"prenc"),
    ("seigel",      r"seigel|seigel|diesect"),
    ("dolese",      r"dolese"),
    ("odeholm",     r"odeholm"),
    ("broco",       r"broco|lancaster|ted jensen"),
    ("silverstein", r"guaiana|silverstein|kalajian|shyeye"),
    ("heavenward",  r"heavenward|tuch|townsend"),
    ("cityofsouls", r"savell|city of souls|merrill|karnivool"),
    ("sunborn",     r"sunborn|leon schmidt|donaldson"),
    ("hamidovic",   r"hamidovic"),
    ("putney",      r"putney"),
    ("lever",       r"lever|sleep token"),
    ("bassal",      r"bassal|thornhill"),
    ("udd",         r"\budd\b|architects"),
    ("braunstein",  r"braunstein|spiritbox"),
    ("cervini",     r"cervini|bad omens"),
    ("bogren",      r"bogren"),
    ("nolly",       r"nolly|getgood"),
    ("kahney",      r"kahney|tesseract"),
    ("cichocki",    r"cichocki|heaving"),
    ("renner",      r"renner|senna"),
    ("sturgis",     r"sturgis|asking alexandria"),
    ("gordon",      r"mick gordon"),
    ("bedan",       r"bedan|keepforest"),
]
CANON_ORDER = [r[0] for r in RULES]

def canon_of(name):
    n = name.lower()
    for cid, pat in RULES:
        if re.search(pat, n):
            return cid
    return None

SLIDER = re.compile(r"^slider(\d+):[^<]*<[^{]*\{(.*)\}>\s*-?\s*(.*)$")

def parse_suite(path):
    best = None
    for line in open(path, encoding="utf-8", errors="ignore"):
        m = SLIDER.match(line.strip())
        if not m:
            continue
        label = m.group(3).lower()
        names = [x.strip() for x in m.group(2).split(",")]
        if any(k in label for k in ("preset", "blueprint", "producer")) and len(names) >= 9:
            best = (int(m.group(1)), names)
    return best

def main():
    suites = {}
    for f in sorted(glob.glob(os.path.join(FX, "Damei_*.jsfx"))):
        r = parse_suite(f)
        if not r:
            continue
        sl, names = r
        suites[os.path.basename(f)] = {
            "slider": sl,
            "count": len(names),
            "canon": [canon_of(n) for n in names],
            "names": names,
        }
    report = {}
    for s, d in suites.items():
        miss = [(i, d["names"][i]) for i, c in enumerate(d["canon"]) if c is None]
        dup = {c for c in d["canon"] if c and d["canon"].count(c) > 1}
        if miss or dup:
            report[s] = {"unmapped": miss, "duplicate_canon": sorted(dup)}
    out = {"canon_order": CANON_ORDER, "suites": suites, "problems": report}
    json.dump(out, open(os.path.join(HERE, "preset_map.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)

    lines = ["// AUTO-GENERATED by tools/gen_preset_map.py - do not edit.",
             "// Canonical producer ids (index into this list):"]
    lines.append("// " + ", ".join(f"{i}={c}" for i, c in enumerate(CANON_ORDER)))
    for s, d in suites.items():
        tag = s.replace("Damei_", "").replace(".jsfx", "").lower()
        to_c = " :\n  ".join(f"i == {i} ? {CANON_ORDER.index(c)}" for i, c in enumerate(d["canon"]) if c)
        lines.append(f"function pm_{tag}_to_canon(i) (\n  {to_c} :\n  -1;\n);")
        from_c = " :\n  ".join(f"c == {CANON_ORDER.index(c)} ? {i}" for i, c in enumerate(d["canon"]) if c)
        lines.append(f"function pm_canon_to_{tag}(c) (\n  {from_c} :\n  -1;\n);")
    open(os.path.join(FX, "Damei_PresetMap.jsfx-inc"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

    print(f"{'suite':32} slider count  mapped")
    for s, d in suites.items():
        print(f"{s:32} {d['slider']:>6} {d['count']:>5}  {sum(1 for c in d['canon'] if c)}/{d['count']}")
    print("problems:", json.dumps(report, ensure_ascii=False, indent=1) if report else "none")

if __name__ == "__main__":
    main()

local f = io.open("c:\\Dev\\DameiSuite\\tools\\reaper_diag2.txt", "w")
local function log(s) f:write(s .. "\n") end
local proj = reaper.EnumProjects(-1)
log("undo: " .. tostring(reaper.Undo_CanUndo2(proj)))
